const {app,BrowserWindow,ipcMain}=require('electron')
const path=require('node:path'),fs=require('node:fs'),assert=require('node:assert/strict')
const root=path.resolve(__dirname,'..'),out=path.join(root,'tests','screenshots')
app.setPath('userData',path.join(root,'tests','.electron-profile'))
let bytes=null
ipcMain.handle('db:load',()=>bytes)
ipcMain.handle('db:save',(_event,data)=>{bytes=data;return {ok:true}})
app.whenReady().then(async()=>{
  fs.mkdirSync(out,{recursive:true})
  const win=new BrowserWindow({show:false,width:1200,height:900,webPreferences:{backgroundThrottling:false,preload:path.join(root,'electron','preload.cjs')}})
  const errors=[]
  win.webContents.on('console-message',(_e,level,message)=>{if(level===3 && !message.includes('Content Security Policy'))errors.push(message)})
  const exec=script=>win.webContents.executeJavaScript(`(()=>eval(${JSON.stringify(script)}))()`)
  async function ready(text) {
    for(let n=0;n<100;n++){if(await exec(`document.body.innerText.includes(${JSON.stringify(text)})`))return;await new Promise(r=>setTimeout(r,100))}
    throw new Error('Не загружено: '+text+' '+await exec('document.body.innerText'))
  }
  async function capture(name){await exec('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');await new Promise(r=>setTimeout(r,150));fs.writeFileSync(path.join(out,name+'.png'),(await win.webContents.capturePage()).toPNG())}
  async function navigate(route,text){await exec(`location.hash=${JSON.stringify(route)}`);await ready(text)}
  try {
    await win.loadFile(path.join(root,'dist','index.html'))
    await ready('Нет начислений за выбранный период');await capture('dashboard')
    await navigate('/settings','Мои счётчики')
    assert.equal(await exec("document.querySelectorAll('[role=switch]').length"),14)
    await exec("document.querySelectorAll('[role=switch]')[1].click()")
    await navigate('/meters','История показаний')
    assert.equal(await exec("document.querySelector('main').innerText.includes('Горячая вода')"),true)
    await navigate('/settings','Мои счётчики')
    assert.equal(await exec("document.querySelectorAll('[role=switch]')[1].checked"),true)
    await exec("document.querySelectorAll('[role=switch]')[1].click()")
    await exec("document.querySelector('[aria-label=\"Сохранить: Мои счётчики\"]').click()")
    await ready('Сохранено ✓');await capture('settings')
    await navigate('/meters','История показаний')
    assert.equal(await exec("document.querySelector('main').innerText.includes('Горячая вода')"),false)
    assert.equal(await exec("document.querySelector('main').innerText.includes('Водоотведение')"),false)
    await navigate('/settings','Мои счётчики')
    await exec("document.querySelectorAll('[role=switch]')[1].click()")
    await exec("document.querySelector('[aria-label=\"Сохранить: Мои счётчики\"]').click()")
    await ready('Сохранено ✓')
    await navigate('/meters','История показаний')
    assert.equal(await exec("document.querySelector('main').innerText.includes('Горячая вода')"),true)
    await capture('meters')
    await navigate('/tariffs','Новый тариф')
    await exec("const select=document.querySelector('main select');const set=Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set;set.call(select,'3');select.dispatchEvent(new Event('change',{bubbles:true}))")
    await ready('Тип тарифа')
    await exec("const select=document.querySelectorAll('main select')[1];Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(select,'tiered');select.dispatchEvent(new Event('change',{bubbles:true}))")
    await ready('3-й диапазон');await capture('tariffs')
    await exec("document.querySelector('main form').requestSubmit()")
    await ready('3 диапазона')
    await exec("document.querySelector('[aria-label=\"Удалить тариф\"]').click()")
    await ready('Удалить тариф?')
    await exec("document.querySelector('[role=dialog] .btn-primary').click()")
    await ready('Тарифы ещё не заданы')
    await exec("document.querySelector('main form').requestSubmit()")
    await ready('3 диапазона')
    assert.equal(await exec("document.querySelectorAll('[aria-label=\"Удалить тариф\"]').length"),1)
    await navigate('/invoices','Новое начисление');await capture('invoices')
    assert.equal(await exec("document.body.innerText.includes('Ручная сумма') || document.body.innerText.includes('Версия 1.')"),false)
    assert.equal(await exec("Array.from(document.querySelectorAll('main select option')).some(o=>o.textContent==='Водоотведение')"),true)
    await win.reload();await ready('Новое начисление')
    assert.ok(bytes.length>0);assert.deepEqual(errors,[])
    console.log('Electron UI smoke: PASS; 5 screenshots; isolated database; meter toggles and reload verified')
    app.exit(0)
  }catch(e){console.error(e);app.exit(1)}
})
